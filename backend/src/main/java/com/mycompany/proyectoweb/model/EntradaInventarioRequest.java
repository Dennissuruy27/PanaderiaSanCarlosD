package com.mycompany.proyectoweb.model;

/**
 *
 * @author Dennis Suruy
 */
public class EntradaInventarioRequest {
    private int idProducto;
    private double cantidadM;
    private String motivo;
    private int idUsuario;

    public EntradaInventarioRequest() {
    }

    public int getIdProducto() {
        return idProducto;
    }

    public void setIdProducto(int idProducto) {
        this.idProducto = idProducto;
    }

    public double getCantidadM() {
        return cantidadM;
    }

    public void setCantidadM(double cantidadM) {
        this.cantidadM = cantidadM;
    }

    public String getMotivo() {
        return motivo;
    }

    public void setMotivo(String motivo) {
        this.motivo = motivo;
    }

    public int getIdUsuario() {
        return idUsuario;
    }

    public void setIdUsuario(int idUsuario) {
        this.idUsuario = idUsuario;
    }
}
